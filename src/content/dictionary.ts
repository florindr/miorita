// Helper functions for easy querying across all stations
export class DictionaryService {
  /** Retrieve all entries matching a difficulty level (1, 2, or 3) */
  static getByDifficulty(difficulty: WordDifficulty): DictionaryEntry[] {
    return ROMANIAN_DICTIONARY.filter((e) => e.difficulty === difficulty);
  }

  /** Retrieve all entries up to and including a max difficulty level */
  static getUpToDifficulty(maxDifficulty: WordDifficulty): DictionaryEntry[] {
    return ROMANIAN_DICTIONARY.filter((e) => e.difficulty <= maxDifficulty);
  }

  /** Retrieve all entries matching a specific gender */
  static getByGender(gender: WordGender): DictionaryEntry[] {
    return ROMANIAN_DICTIONARY.filter((e) => e.gender === gender);
  }

  /** Retrieve a randomized batch of words matching level, without immediate repeats */
  static getRandomBatch(
    count: number = 6,
    level: WordDifficulty = 1,
    excludeIds: string[] = []
  ): DictionaryEntry[] {
    const candidates = ROMANIAN_DICTIONARY.filter(
      (e) => e.difficulty <= level && !excludeIds.includes(e.id)
    );

    const pool = candidates.length >= count ? candidates : ROMANIAN_DICTIONARY;
    const shuffled = shuffleArray(pool);

    // Ensure a balanced distribution of genders across the batch if possible
    const masculins = shuffled.filter((e) => e.gender === 'masculin');
    const feminins = shuffled.filter((e) => e.gender === 'feminin');
    const neutrus = shuffled.filter((e) => e.gender === 'neutru');

    const result: DictionaryEntry[] = [];
    const minPerGender = Math.max(1, Math.floor(count / 3));

    // Pick at least minPerGender of each gender for pedagogical balance
    result.push(...masculins.slice(0, minPerGender));
    result.push(...feminins.slice(0, minPerGender));
    result.push(...neutrus.slice(0, minPerGender));

    // Fill the remainder from the shuffled pool
    for (const item of shuffled) {
      if (result.length >= count) break;
      if (!result.some((r) => r.id === item.id)) {
        result.push(item);
      }
    }

    return shuffleArray(result);
  }
}
