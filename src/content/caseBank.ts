export class CaseService {
  /** Retrieve all items matching a difficulty level (1, 2, or 3) */
  static getByDifficulty(difficulty: CaseDifficulty): CaseItem[] {
    return CASE_BANK.filter((e) => e.difficulty === difficulty);
  }

  /** Retrieve all items up to and including a max difficulty level */
  static getUpToDifficulty(maxDifficulty: CaseDifficulty): CaseItem[] {
    return CASE_BANK.filter((e) => e.difficulty <= maxDifficulty);
  }

  /** Retrieve a randomized batch of items matching level, without immediate repeats */
  static getRandomBatch(
    count: number = 5,
    level: CaseDifficulty = 1,
    excludeIds: string[] = []
  ): CaseItem[] {
    const candidates = CASE_BANK.filter(
      (e) => e.difficulty <= level && !excludeIds.includes(e.id)
    );

    const pool = candidates.length >= count ? candidates : CASE_BANK;
    const shuffled = shuffleArray(pool);

    const result = shuffled.slice(0, count);
    return shuffleArray(result);
  }
}
