export class ArticleService {
  /** Retrieve all items matching a difficulty level (1, 2, or 3) */
  static getByDifficulty(difficulty: ArticleDifficulty): ArticleItem[] {
    return ARTICLE_BANK.filter((e) => e.difficulty === difficulty);
  }

  /** Retrieve all items up to and including a max difficulty level */
  static getUpToDifficulty(maxDifficulty: ArticleDifficulty): ArticleItem[] {
    return ARTICLE_BANK.filter((e) => e.difficulty <= maxDifficulty);
  }

  /** Retrieve a randomized batch of items matching level, without immediate repeats */
  static getRandomBatch(
    count: number = 6,
    level: ArticleDifficulty = 1,
    excludeIds: string[] = []
  ): ArticleItem[] {
    const candidates = ARTICLE_BANK.filter(
      (e) => e.difficulty <= level && !excludeIds.includes(e.id)
    );

    const pool = candidates.length >= count ? candidates : ARTICLE_BANK;
    const shuffled = shuffleArray(pool);

    const result = shuffled.slice(0, count);
    return shuffleArray(result);
  }
}
