export class CalqueService {
  /** Retrieve all items matching a difficulty level (1, 2, or 3) */
  static getByDifficulty(difficulty: CalqueDifficulty): CalqueItem[] {
    return CALQUE_BANK.filter((e) => e.difficulty === difficulty);
  }

  /** Retrieve all items up to and including a max difficulty level */
  static getUpToDifficulty(maxDifficulty: CalqueDifficulty): CalqueItem[] {
    return CALQUE_BANK.filter((e) => e.difficulty <= maxDifficulty);
  }

  /** Retrieve a randomized batch of items matching level, without immediate repeats */
  static getRandomBatch(
    count: number = 5,
    level: CalqueDifficulty = 1,
    excludeIds: string[] = []
  ): CalqueItem[] {
    const candidates = CALQUE_BANK.filter(
      (e) => e.difficulty <= level && !excludeIds.includes(e.id)
    );

    const pool = candidates.length >= count ? candidates : CALQUE_BANK;
    const shuffled = shuffleArray(pool);

    const result = shuffled.slice(0, count);
    return shuffleArray(result);
  }
}
